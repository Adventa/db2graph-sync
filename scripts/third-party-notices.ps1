# Regenerates THIRD_PARTY_NOTICES.md from `cargo metadata` (all features, so
# the list is a superset of every supported build). Run before each release.
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
Set-Location $root
$m = cargo metadata --format-version 1 --all-features --locked | ConvertFrom-Json
$ids = @{}
foreach ($n in $m.resolve.nodes) { $ids[$n.id] = 1 }
$pkgs = $m.packages | Where-Object { $ids.ContainsKey($_.id) -and $_.source } | Sort-Object name, version
$lines = @()
$lines += '# Third-party notices'
$lines += ''
$lines += 'db2graph-sync — an open-source project by Adventa. Licensed under Apache-2.0 (see LICENSE and NOTICE).'
$lines += ''
$lines += 'This file lists every third-party crate that can be compiled into db2graph-sync or'
$lines += 'db2graph-sync-cli (all cargo features enabled), with the license expression declared'
$lines += 'by each crate. It is generated by `scripts/third-party-notices.ps1` (or `.sh`) from'
$lines += '`cargo metadata`; do not edit by hand.'
$lines += ''
$lines += 'Obligations: most dependencies are MIT and/or Apache-2.0. Binary and container'
$lines += 'distributions must include the license texts and copyright notices of their'
$lines += 'dependencies (the release procedure bundles them; see RELEASING.md). Notable'
$lines += 'attribution requirements: `ring` (ISC AND Apache-2.0, includes BoringSSL/OpenSSL-derived'
$lines += 'code under ISC-style terms), `webpki-roots` data (CDLA-Permissive-2.0), Unicode data'
$lines += 'crates (Unicode-3.0), and BSD-licensed crates (retain copyright notices).'
$lines += ''
$lines += 'External services (databases, cloud services, embedding providers) and any FIPS'
$lines += 'cryptographic module an integrator supplies are governed by their own terms.'
$lines += ''
$lines += "| Crate | Version | License | Repository |"
$lines += "|-------|---------|---------|------------|"
foreach ($p in $pkgs) {
  $lic = if ($p.license) { $p.license } else { "see crate (license-file)" }
  $repo = if ($p.repository) { $p.repository } else { "" }
  $lines += "| $($p.name) | $($p.version) | $lic | $repo |"
}
$lines += ''
$lines += "Total: $($pkgs.Count) crates."
Set-Content -Path (Join-Path $root 'THIRD_PARTY_NOTICES.md') -Value ($lines -join "`n") -Encoding utf8NoBOM
Write-Output "wrote THIRD_PARTY_NOTICES.md ($($pkgs.Count) crates)"
