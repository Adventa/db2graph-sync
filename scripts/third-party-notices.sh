#!/usr/bin/env bash
# Regenerates THIRD_PARTY_NOTICES.md from `cargo metadata` (all features).
# Requires jq. Equivalent to scripts/third-party-notices.ps1.
set -euo pipefail
cd "$(dirname "$0")/.."
meta=$(cargo metadata --format-version 1 --all-features --locked)
{
  echo '# Third-party notices'
  echo
  echo 'db2graph-sync — an open-source project by Adventa. Licensed under Apache-2.0 (see LICENSE and NOTICE).'
  echo
  echo 'This file lists every third-party crate that can be compiled into db2graph-sync or'
  echo 'db2graph-sync-cli (all cargo features enabled), with the license expression declared'
  echo 'by each crate. It is generated by `scripts/third-party-notices.ps1` (or `.sh`) from'
  echo '`cargo metadata`; do not edit by hand.'
  echo
  echo 'Obligations: most dependencies are MIT and/or Apache-2.0. Binary and container'
  echo 'distributions must include the license texts and copyright notices of their'
  echo 'dependencies (the release procedure bundles them; see RELEASING.md). Notable'
  echo 'attribution requirements: `ring` (ISC AND Apache-2.0, includes BoringSSL/OpenSSL-derived'
  echo 'code under ISC-style terms), `webpki-roots` data (CDLA-Permissive-2.0), Unicode data'
  echo 'crates (Unicode-3.0), and BSD-licensed crates (retain copyright notices).'
  echo
  echo 'External services (databases, cloud services, embedding providers) and any FIPS'
  echo 'cryptographic module an integrator supplies are governed by their own terms.'
  echo
  echo '| Crate | Version | License | Repository |'
  echo '|-------|---------|---------|------------|'
  echo "$meta" | jq -r '
    ([.resolve.nodes[].id] | map({(.) : true}) | add) as $used
    | [.packages[] | select(.source != null and $used[.id])]
    | sort_by(.name, .version)[]
    | "| \(.name) | \(.version) | \(.license // "see crate (license-file)") | \(.repository // "") |"'
  echo
  echo "Total: $(echo "$meta" | jq '([.resolve.nodes[].id] | map({(.) : true}) | add) as $u | [.packages[] | select(.source != null and $u[.id])] | length') crates."
} > THIRD_PARTY_NOTICES.md
echo "wrote THIRD_PARTY_NOTICES.md"
